// DocsOptions controls the Markdown rendered by `vpnmap docs`.
type DocsOptions struct {
	// Commit is the git commit the files come from ("" if unknown).
	Commit string
	Dirty  bool
	// Now is the generation time (shown in Asia/Tehran).
	Now time.Time
	// Status optionally adds a status column: keys "node:<id>",
	// "link:<id>", "route:<id>" → ok | degraded | down | unknown.
	Status map[string]string
	// StatusAt is when the live status was read.
	StatusAt string
}

// Docs renders Notion page 01 (architecture) from the bundle: a Mermaid
// flowchart with one frame per group and the tables of nodes, links,
// routes and alerts. The topology files are the source of truth; the page
// is regenerated after every `vpnmap apply`.
func Docs(b *Bundle, opt DocsOptions) string {
	var w strings.Builder
	name := b.Map.Name
	if name == "" {
		name = "VPN topology"
	}
	fmt.Fprintf(&w, "# %s — topology\n\n", name)
	when := opt.Now
	if when.IsZero() {
		when = time.Now()
	}
	loc := docsLocation(b.Map.Settings.Timezone)
	commit := opt.Commit
	if commit == "" {
		commit = "uncommitted"
	} else if opt.Dirty {
		commit += " + uncommitted changes"
	}
	fmt.Fprintf(&w, "> Generated by `vpnmap docs` from `topology/` (commit %s) on %s. Do not edit this page by hand: change the topology files, run `vpnmap apply`, then regenerate it.\n",
		commit, when.In(loc).Format("2006-01-02 15:04")+" "+zoneName(when.In(loc)))
	if opt.Status != nil {
		at := opt.StatusAt
		if at == "" {
			at = "now"
		}
		fmt.Fprintf(&w, "> The status columns are a live snapshot from the hub (%s), not part of the topology.\n", at)
	}
	w.WriteString("\n")
	fmt.Fprintf(&w, "%d nodes · %d links · %d routes · %d alert rules · %d components\n\n", len(b.Nodes), len(b.Links), len(b.Routes), len(b.Alerts), len(b.Components))

	w.WriteString("## Map\n\n")
	w.WriteString("Solid arrows carry user traffic (data plane); dotted arrows are control-plane connections. Labels give the link label and protocol.\n\n")
	w.WriteString("```mermaid\n")
	w.WriteString(Mermaid(b))
	w.WriteString("```\n\n")

	status := func(kind, id string) string {
		if s, ok := opt.Status[kind+":"+id]; ok && s != "" {
			return statusMark(s)
		}
		return "–"
	}
	live := opt.Status != nil

	// Nodes.
	w.WriteString("## Nodes\n\n")
	head := []string{"ID", "Name", "Address", "Group", "Role", "Agent"}
	if live {
		head = append(head, "Status")
	}
	rows := [][]string{}
	for _, n := range b.Nodes {
		agent := "no"
		if n.Agent {
			agent = "yes"
		}
		r := []string{code(n.ID), n.Name, strings.Join(n.Address, ", "), groupTitle(b, n.Group), n.Role, agent}
		if live {
			r = append(r, status("node", n.ID))
		}
		rows = append(rows, r)
	}
	mdTable(&w, head, rows)

	// Links.
	w.WriteString("## Links\n\n")
	head = []string{"Label", "From → To", "Plane", "Protocol", "Traffic source", "Health checks"}
	if live {
		head = append(head, "Status")
	}
	rows = nil
	for _, l := range b.Links {
		label := l.Label
		if label == "" {
			label = l.ID
		}
		label = code(label)
		if l.Title != "" {
			label += " " + l.Title
		}
		traffic := "–"
		if l.Traffic != nil {
			traffic = CheckSummary(l.Traffic)
			if l.Traffic.Fallback != nil {
				traffic += " (fallback: " + CheckSummary(l.Traffic.Fallback) + ")"
			}
		}
		var health []string
		for i := range l.Health {
			health = append(health, CheckSummary(&l.Health[i]))
		}
		if l.Conns != nil {
			health = append(health, "conns: "+CheckSummary(l.Conns))
		}
		r := []string{label, nodeName(b, l.From) + " → " + nodeName(b, l.To), l.Plane, l.Protocol, traffic, orNone(strings.Join(health, "; "))}
		if live {
			r = append(r, status("link", l.ID))
		}
		rows = append(rows, r)
	}
	mdTable(&w, head, rows)

	// Routes.
	w.WriteString("## Routes\n\n")
	head = []string{"Route", "Hops", "Squads", "Users", "Probe", "If broken"}
	if live {
		head = append(head, "Status")
	}
	rows = nil
	for _, r := range b.Routes {
		var hops []string
		for _, h := range r.Hops {
			if l := b.LinkByID(h); l != nil && l.Label != "" {
				hops = append(hops, l.Label)
			} else {
				hops = append(hops, h)
			}
		}
		users := "–"
		switch {
		case r.Users != nil && r.UsersEstimate > 0:
			users = fmt.Sprintf("live (%s), ≈%s", CheckSummary(r.Users), groupThousands(r.UsersEstimate))
		case r.Users != nil:
			users = "live (" + CheckSummary(r.Users) + ")"
		case r.UsersEstimate > 0:
			users = "≈" + groupThousands(r.UsersEstimate)
		}
		probe := "–"
		if r.Probe != nil {
			probe = CheckSummary(r.Probe)
		}
		row := []string{code(r.ID) + " " + r.Title, strings.Join(hops, " → "), orNone(strings.Join(r.Squads, ", ")), users, probe, r.Impact}
		if live {
			row = append(row, status("route", r.ID))
		}
		rows = append(rows, row)
	}
	mdTable(&w, head, rows)

	// Alerts.
	w.WriteString("## Alerts\n\n")
	rows = nil
	for _, a := range b.Alerts {
		rows = append(rows, []string{code(a.ID), code(a.When), a.Severity, a.MessageFa})
	}
	mdTable(&w, []string{"ID", "When", "Severity", "Message (fa)"}, rows)

	// Components.
	w.WriteString("## Components\n\n")
	rows = nil
	for _, c := range b.Components {
		docs := "–"
		if c.Docs != "" {
			docs = "[Notion](" + c.Docs + ")"
		}
		rows = append(rows, []string{code(c.Component), c.Title, code(c.File), docs})
	}
	mdTable(&w, []string{"Component", "Title", "File", "Docs"}, rows)
	return w.String()
}

// Mermaid renders the topology as a `flowchart LR` (without the fences).
func Mermaid(b *Bundle) string {
	var w strings.Builder
	w.WriteString("flowchart LR\n")
	byGroup := map[string][]Node{}
	for _, n := range b.Nodes {
		byGroup[n.Group] = append(byGroup[n.Group], n)
	}
	placed := map[string]bool{}
	for _, g := range b.Map.Groups {
		nodes := byGroup[g.ID]
		if len(nodes) == 0 {
			continue
		}
		framed := g.Kind != "external"
		if g.Frame != nil {
			framed = *g.Frame
		}
		indent := "  "
		if framed {
			fmt.Fprintf(&w, "  subgraph %s[\"%s\"]\n", mermaidID("g", g.ID), MermaidLabel(g.Title))
			indent = "    "
		}
		for _, n := range nodes {
			w.WriteString(indent + mermaidNode(n) + "\n")
			placed[n.ID] = true
		}
		if framed {
			w.WriteString("  end\n")
		}
	}
	for _, n := range b.Nodes { // nodes of undeclared groups (invalid topology)
		if !placed[n.ID] {
			w.WriteString("  " + mermaidNode(n) + "\n")
		}
	}
	for _, l := range b.Links {
		arrow := "-->"
		if l.Plane == "control" {
			arrow = "-.->"
		}
		label := l.Label
		if label == "" {
			label = l.ID
		}
		if l.Protocol != "" {
			label += " · " + l.Protocol
		}
		fmt.Fprintf(&w, "  %s %s|\"%s\"| %s\n", mermaidID("n", l.From), arrow, MermaidLabel(label), mermaidID("n", l.To))
	}
	return w.String()
}

func mermaidNode(n Node) string {
	label := MermaidLabel(n.Name)
	if len(n.Address) > 0 {
		label += "<br/>" + MermaidLabel(n.Address[0])
	}
	id := mermaidID("n", n.ID)
	switch n.Kind {
	case "users":
		return fmt.Sprintf("%s([\"%s\"])", id, label)
	case "internet":
		return fmt.Sprintf("%s((\"%s\"))", id, label)
	}
	return fmt.Sprintf("%s[\"%s\"]", id, label)
}

var reMermaidID = regexp.MustCompile(`[^A-Za-z0-9_]`)

// mermaidID makes a safe identifier ("relay-1" → "n_relay_1"); the prefix
// avoids Mermaid keywords such as end, graph or subgraph.
func mermaidID(prefix, id string) string {
	return prefix + "_" + reMermaidID.ReplaceAllString(id, "_")
}

// MermaidLabel escapes text for a double-quoted Mermaid label: quotes, angle
// brackets and characters with a meaning in Mermaid syntax become entity
// codes, and line breaks become spaces.
func MermaidLabel(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString("#quot;")
		case '<':
			b.WriteString("#lt;")
		case '>':
			b.WriteString("#gt;")
		case '#':
			b.WriteString("#35;")
		case '|':
			b.WriteString("#124;")
		case '`':
			b.WriteString("#96;")
		case '&':
			b.WriteString("#amp;")
		case '\n', '\r', '\t':
			b.WriteByte(' ')
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

// CheckSummary describes a check in a few words for tables and the CLI,
// e.g. "tcp-connect from probe → relay-1.aitopology.ir:2053".
func CheckSummary(c *Check) string {
	if c == nil {
		return "–"
	}
	at := func() string {
		if h := c.Str("host"); h != "" {
			return " @ " + h
		}
		return ""
	}
	s := c.Collector
	switch c.Collector {
	case "tcp-connect":
		s += " from " + firstNonEmptyStr(c.Str("from"), "probe") + " → " + c.Str("target")
	case "http-probe":
		s += " from " + firstNonEmptyStr(c.Str("from"), "hub") + " → " + c.Str("url")
	case "tls-expiry":
		s += " " + c.Str("host")
		if cn := c.Str("connect"); cn != "" {
			s += " (origin " + cn + ")"
		}
	case "ss-conns":
		ports := intList(c.Params["ports"])
		if len(ports) == 0 {
			ports = intList(c.Params["port"])
		}
		var ps []string
		for _, p := range ports {
			ps = append(ps, fmt.Sprint(p))
		}
		s += at() + " :" + strings.Join(ps, ",")
		if side := c.Str("side"); side == "remote" {
			s += " (remote)"
		}
	case "nic-counter":
		s += at() + " " + firstNonEmptyStr(c.Str("interface"), "*")
	case "wg-transfer", "wg-handshake":
		iface := c.Str("interface")
		if ns := c.Str("netns"); ns != "" {
			iface = ns + "/" + iface
		}
		s += at() + " " + iface
	case "xray-stats":
		s += at() + " " + c.Str("node") + " " + firstNonEmptyStr(c.Str("outbound"), c.Str("inbound"))
	case "remnawave-node":
		s += " " + c.Str("node")
	case "remnawave-online":
		if n := c.Str("node"); n != "" {
			s += " " + n
		}
	case "xbridger-connection":
		s += at() + " " + c.Str("connection")
	case "3xui-inbound":
		s += " " + c.Str("panel") + "/" + c.Str("inbound")
	case "systemd-unit":
		s += at() + " " + SystemdUnitName(c)
	case "docker-container":
		s += at() + " " + c.Str("container")
	case "log-match":
		s += at() + " " + c.Str("path")
	case "local-check":
		s += at() + " " + c.Str("check")
	case "e2e-probe":
		if cc := c.Str("expect_country"); cc != "" {
			s += " expect " + cc
		}
	default:
		s += at()
	}
	return strings.TrimSpace(s)
}

func mdTable(w *strings.Builder, head []string, rows [][]string) {
	if len(rows) == 0 {
		w.WriteString("_none_\n\n")
		return
	}
	w.WriteString("| " + strings.Join(head, " | ") + " |\n")
	seps := make([]string, len(head))
	for i := range seps {
		seps[i] = "---"
	}
	w.WriteString("| " + strings.Join(seps, " | ") + " |\n")
	for _, r := range rows {
		cells := make([]string, len(r))
		for i, c := range r {
			cells[i] = mdCell(c)
		}
		w.WriteString("| " + strings.Join(cells, " | ") + " |\n")
	}
	w.WriteString("\n")
}

// mdCell keeps a value on one table row.
func mdCell(s string) string {
	s = strings.ReplaceAll(s, "\r", "")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", `\|`)
	if strings.TrimSpace(s) == "" {
		return "–"
	}
	return s
}

func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + strings.ReplaceAll(s, "`", "'") + "`"
}

func orNone(s string) string {
	if s == "" {
		return "–"
	}
	return s
}

func statusMark(s string) string {
	switch s {
	case "ok":
		return "🟢 ok"
	case "degraded":
		return "🟠 degraded"
	case "down":
		return "🔴 down"
	}
	return "⚪ " + s
}

func groupTitle(b *Bundle, id string) string {
	for _, g := range b.Map.Groups {
		if g.ID == id {
			return g.Title
		}
	}
	return id
}

func nodeName(b *Bundle, id string) string {
	if n := b.NodeByID(id); n != nil {
		return n.Name
	}
	return id
}

func groupThousands(n int) string {
	s := fmt.Sprint(n)
	var parts []string
	for len(s) > 3 {
		parts = append([]string{s[len(s)-3:]}, parts...)
		s = s[:len(s)-3]
	}
	return strings.Join(append([]string{s}, parts...), ",")
}

func docsLocation(tz string) *time.Location {
	if tz == "" {
		tz = "Asia/Tehran"
	}
	if l, err := time.LoadLocation(tz); err == nil {
		return l
	}
	return time.FixedZone("IRST", 3*3600+1800)
}

func zoneName(t time.Time) string {
	if t.Location().String() == "Asia/Tehran" || t.Location().String() == "IRST" {
		return "IRST"
	}
	return t.Format("MST")
}
