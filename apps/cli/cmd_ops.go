// TypesGenPath is the hub's copy of the closed action types.
const TypesGenPath = "apps/hub/src/ops/types.gen.json"

func cmdOps() *cobra.Command {
	c := &cobra.Command{
		Use:   "ops",
		Short: "Ops action types, per-server runner configs and grant commands",
		Long: `Ops actions are the only way the Telegram assistant can read or change a
server (docs/ops-actions.md). The action types are closed (pkg/ops); what they
may touch on a server is the node's ops: block. These commands print files and
commands for you to install; vpnmap never connects to a server.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error { return cmd.Help() },
	}
	c.AddCommand(opsTypesCmd(), opsConfigCmd(), opsShowCmd())
	return c
}

// TypesJSON is the generated hub copy of ops.Types.
func TypesJSON() ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	err := enc.Encode(map[string]any{
		"$comment":  "Generated by `vpnmap ops types --write` from pkg/ops/types.go. Do not edit.",
		"types":     ops.Types,
		"max_token": ops.MaxToken,
		"max_line":  ops.MaxLine,
	})
	return buf.Bytes(), err
}

func opsTypesCmd() *cobra.Command {
	var write, check bool
	c := &cobra.Command{
		Use:   "types",
		Short: "List the closed ops action types (--write/--check the hub's copy)",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			raw, err := TypesJSON()
			if err != nil {
				return err
			}
			if write || check {
				root, err := repoRoot()
				if err != nil {
					return err
				}
				p := filepath.Join(root, TypesGenPath)
				if check {
					old, _ := os.ReadFile(p)
					if !bytes.Equal(old, raw) {
						return failf("%s is out of date: run `vpnmap ops types --write`", TypesGenPath)
					}
					fmt.Println("✓ " + TypesGenPath + " is up to date")
					return nil
				}
				if err := os.WriteFile(p, raw, 0o644); err != nil {
					return err
				}
				fmt.Println("wrote " + TypesGenPath)
				return nil
			}
			if g.JSON {
				_, err := os.Stdout.Write(raw)
				return err
			}
			for _, t := range ops.Types {
				var ps []string
				for _, p := range t.Params {
					if p.Source == ops.FromFixed {
						ps = append(ps, p.Name+"∈{"+strings.Join(p.Enum, ",")+"}")
					} else {
						ps = append(ps, p.Name+"←"+p.Source)
					}
				}
				fmt.Printf("%-18s %-6s %-9s %s\n", t.Name, t.Kind, t.Where, strings.Join(ps, " "))
			}
			return nil
		},
	}
	c.Flags().BoolVar(&write, "write", false, "write "+TypesGenPath)
	c.Flags().BoolVar(&check, "check", false, "fail if "+TypesGenPath+" is stale (CI)")
	return c
}

// OpsConfigYAML renders the runner config file with a header.
func OpsConfigYAML(cfg *ops.RunnerConfig) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# /etc/vpnmap-ops/ops.yaml for %s, generated by `vpnmap ops config %s`.\n", cfg.Node, cfg.Node)
	fmt.Fprintf(&buf, "# Install root-owned, mode 0644. Hash %s. Do not edit by hand.\n", cfg.Hash())
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(cfg); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func opsConfigCmd() *cobra.Command {
	return &cobra.Command{
		Use:   "config <node>",
		Short: "Print /etc/vpnmap-ops/ops.yaml for a node (generated from the topology)",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if err := noAt("ops config"); err != nil {
				return err
			}
			b, _, err := validBundle()
			if err != nil {
				return err
			}
			cfg, err := topology.OpsConfig(b, args[0])
			if err != nil {
				return failf("%v", err)
			}
			raw, err := OpsConfigYAML(cfg)
			if err != nil {
				return err
			}
			if g.JSON {
				return printJSON(map[string]any{"node": cfg.Node, "config_hash": cfg.Hash(), "config": cfg, "yaml": string(raw)})
			}
			_, err = os.Stdout.Write(raw)
			return err
		},
	}
}

func opsShowCmd() *cobra.Command {
	return &cobra.Command{
		Use:   "show [node]",
		Short: "Show the resolved ops policy (what the assistant may read or change) per node",
		Args:  cobra.MaximumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			b, _, err := validBundle()
			if err != nil {
				return err
			}
			var out []ops.NodePolicy
			for _, p := range b.Ops {
				if len(args) == 0 || p.Node == args[0] {
					out = append(out, p)
				}
			}
			if len(args) == 1 && len(out) == 0 {
				return failf("node %q has no ops: block", args[0])
			}
			if g.JSON {
				return printJSON(out)
			}
			for _, p := range out {
				fmt.Printf("%s", p.Node)
				if p.Runner {
					fmt.Printf("  runner config %s", p.ConfigHash)
				}
				if p.CutsUsers {
					fmt.Printf("  ⚠ disruptive changes cut paying users (%s)", strings.Join(p.CutRoutes, ", "))
				}
				fmt.Println()
				if c := p.Config; c != nil {
					var restart []string
					for _, x := range c.Containers {
						if x.Restart {
							restart = append(restart, "container "+x.Name)
						}
					}
					for _, x := range c.Units {
						if x.Restart {
							restart = append(restart, "unit "+x.Name)
						}
					}
					for _, s := range c.Scripts {
						if s.Kind == ops.Change {
							restart = append(restart, "script "+s.ID)
						}
					}
					fmt.Printf("  read: %d containers, %d units, %d logs, %d targets, %d ports, %d wg, %d scripts\n",
						len(c.Containers), len(c.Units), len(c.Logs), len(c.TCPTargets), len(c.Ports), len(c.WG), len(c.Scripts))
					if len(restart) > 0 {
						fmt.Printf("  change: %s\n", strings.Join(restart, ", "))
					}
				}
				if p.Remnawave != nil {
					fmt.Printf("  remnawave %s: %s\n", p.Remnawave.Name, strings.Join(p.Remnawave.Actions, ", "))
				}
				if len(p.NeverRestart) > 0 {
					fmt.Printf("  never restart: %s\n", strings.Join(p.NeverRestart, ", "))
				}
				fmt.Printf("  verify: %s\n", strings.Join(p.Verify, " "))
			}
			return nil
		},
	}
}
